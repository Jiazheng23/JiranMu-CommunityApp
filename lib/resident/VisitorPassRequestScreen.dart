import 'package:flutter/material.dart';
import 'package:supabase_flutter/supabase_flutter.dart';
import 'package:intl/intl.dart';

class VisitorPassRequestScreen extends StatefulWidget {
  const VisitorPassRequestScreen({super.key});

  @override
  State<VisitorPassRequestScreen> createState() =>
      _VisitorPassRequestScreenState();
}

class _VisitorPassRequestScreenState
    extends State<VisitorPassRequestScreen> {
  // ── Supabase ──────────────────────────────────────────────────────────────
  final _client = Supabase.instance.client;

  // ── Form controllers ──────────────────────────────────────────────────────
  final _nameCtrl   = TextEditingController();
  final _icCtrl     = TextEditingController();
  final _notesCtrl  = TextEditingController();

  // ── Form state ────────────────────────────────────────────────────────────
  // Purpose options: visiting, delivery, contractor, event_guest
  String   _purpose   = 'visiting';
  DateTime _validDate = DateTime.now().add(const Duration(days: 1));
  bool     _loading   = false;

  // ── Theme ─────────────────────────────────────────────────────────────────
  static const Color _primary = Color(0xFF9A4B3C);
  static const Color _bgPage  = Color(0xFFF5F1ED);

  // Purpose metadata — label, icon, description shown under the chip row
  static const _purposes = [
    (
    value: 'visiting',
    label: 'Visiting',
    icon: Icons.person_outline_rounded,
    ),
    (
    value: 'delivery',
    label: 'Delivery',
    icon: Icons.local_shipping_outlined,
    ),
    (
    value: 'contractor',
    label: 'Contractor',
    icon: Icons.build_outlined,
    ),
    (
    value: 'event_guest',
    label: 'Event Guest',
    icon: Icons.celebration_outlined,
    ),
  ];

  // ── Lifecycle ─────────────────────────────────────────────────────────────

  @override
  void dispose() {
    _nameCtrl.dispose();
    _icCtrl.dispose();
    _notesCtrl.dispose();
    super.dispose();
  }

  // ── Submit ────────────────────────────────────────────────────────────────

  Future<void> _submit() async {
    // Basic validation
    if (_nameCtrl.text.trim().isEmpty) {
      _snack('Please enter the visitor\'s name.');
      return;
    }

    setState(() => _loading = true);
    try {
      final userId = _client.auth.currentUser!.id;

      await _client.from('visitor_passes').insert({
        'resident_id':  userId,
        'visitor_name': _nameCtrl.text.trim(),
        'visitor_ic':
        _icCtrl.text.trim().isEmpty ? null : _icCtrl.text.trim(),
        'purpose':      _purpose,
        'notes':
        _notesCtrl.text.trim().isEmpty ? null : _notesCtrl.text.trim(),
        'valid_date': DateFormat('yyyy-MM-dd').format(_validDate),
        'status':     'pending',
        // qr_token is auto-generated by gen_random_uuid() default in Supabase
      });

      if (!mounted) return;
      Navigator.pop(context, true); // true = refresh the list
      _snack('Visitor pass requested! Awaiting admin approval.');
    } catch (e) {
      _snack('Error: $e');
    } finally {
      if (mounted) setState(() => _loading = false);
    }
  }

  void _snack(String msg) {
    if (!mounted) return;
    ScaffoldMessenger.of(context)
        .showSnackBar(SnackBar(content: Text(msg)));
  }

  // ── Date picker ───────────────────────────────────────────────────────────

  Future<void> _pickDate() async {
    final picked = await showDatePicker(
      context:     context,
      initialDate: _validDate,
      firstDate:   DateTime.now(),
      // Passes valid within the next 30 days
      lastDate:    DateTime.now().add(const Duration(days: 30)),
      builder: (context, child) => Theme(
        data: Theme.of(context).copyWith(
          colorScheme: const ColorScheme.light(
            primary:   _primary,
            onPrimary: Colors.white,
          ),
        ),
        child: child!,
      ),
    );
    if (picked != null) setState(() => _validDate = picked);
  }

  // ── Build ─────────────────────────────────────────────────────────────────

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: _bgPage,
      appBar: AppBar(
        title: const Text(
          'Request Visitor Pass',
          style: TextStyle(
              color: Colors.white,
              fontWeight: FontWeight.w700,
              fontSize: 17),
        ),
        backgroundColor:  _primary,
        foregroundColor:  Colors.white,
        elevation:        0,
        centerTitle:      true,
        leading: IconButton(
          icon: const Icon(Icons.arrow_back_ios_new_rounded, size: 18),
          onPressed: () => Navigator.pop(context),
        ),
      ),
      body: SingleChildScrollView(
        padding: const EdgeInsets.fromLTRB(20, 20, 20, 40),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            // ── Visitor details ──────────────────────────────────────
            _sectionLabel('Visitor Details'),
            const SizedBox(height: 10),
            _card(children: [
              _textField(
                controller:  _nameCtrl,
                label:       'Visitor Full Name',
                icon:        Icons.person_outline_rounded,
                required:    true,
              ),
              const SizedBox(height: 14),
              _textField(
                controller: _icCtrl,
                label:      'IC / Passport Number',
                icon:       Icons.badge_outlined,
                required:   false,
              ),
            ]),
            const SizedBox(height: 20),

            // ── Purpose ──────────────────────────────────────────────
            _sectionLabel('Purpose of Visit'),
            const SizedBox(height: 10),
            _card(children: [
              _purposeGrid(),
              const SizedBox(height: 14),
              _textField(
                controller: _notesCtrl,
                label:      'Additional Notes',
                icon:       Icons.notes_rounded,
                required:   false,
                maxLines:   2,
              ),
            ]),
            const SizedBox(height: 20),

            // ── Visit date ───────────────────────────────────────────
            _sectionLabel('Visit Date'),
            const SizedBox(height: 10),
            _card(children: [
              _datePicker(),
              const SizedBox(height: 10)
            ]),
            const SizedBox(height: 28),

            // ── Submit ───────────────────────────────────────────────
            _submitButton()
          ],
        ),
      ),
    );
  }

  // ── Sub-widgets ───────────────────────────────────────────────────────────
  Widget _sectionLabel(String label) {
    return Text(
      label,
      style: const TextStyle(
          fontSize:   13,
          fontWeight: FontWeight.w700,
          color:      Colors.black54,
          letterSpacing: 0.3),
    );
  }

  Widget _card({required List<Widget> children}) {
    return Container(
      width:   double.infinity,
      padding: const EdgeInsets.all(16),
      decoration: BoxDecoration(
        color:        Colors.white,
        borderRadius: BorderRadius.circular(18),
        boxShadow: [
          BoxShadow(
              color:      Colors.black.withOpacity(0.05),
              blurRadius: 10,
              offset:     const Offset(0, 4)),
        ],
      ),
      child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: children),
    );
  }

  Widget _textField({
    required TextEditingController controller,
    required String label,
    required IconData icon,
    required bool required,
    int maxLines = 1,
  }) {
    return TextFormField(
      controller: controller,
      maxLines:   maxLines,
      style: const TextStyle(fontSize: 14, color: Colors.black87),
      decoration: InputDecoration(
        labelText: required ? '$label *' : label,
        prefixIcon: Icon(icon, size: 18, color: _primary.withOpacity(0.7)),
        alignLabelWithHint: maxLines > 1,
        border: OutlineInputBorder(
          borderRadius: BorderRadius.circular(12),
          borderSide:   const BorderSide(color: Colors.black12),
        ),
        enabledBorder: OutlineInputBorder(
          borderRadius: BorderRadius.circular(12),
          borderSide:   const BorderSide(color: Colors.black12),
        ),
        focusedBorder: OutlineInputBorder(
          borderRadius: BorderRadius.circular(12),
          borderSide:   const BorderSide(color: _primary, width: 1.5),
        ),
        filled:      true,
        fillColor:   Colors.grey.shade50,
        contentPadding: EdgeInsets.symmetric(
            horizontal: 14, vertical: maxLines > 1 ? 14 : 12),
        isDense: true,
      ),
    );
  }

  // 2x2 grid of purpose chips
  Widget _purposeGrid() {
    return GridView.count(
      crossAxisCount: 2,
      shrinkWrap:     true,
      physics:        const NeverScrollableScrollPhysics(),
      crossAxisSpacing: 10,
      mainAxisSpacing:  10,
      childAspectRatio: 2.8,
      children: _purposes.map((p) {
        final isSelected = _purpose == p.value;
        return GestureDetector(
          onTap: () => setState(() => _purpose = p.value),
          child: AnimatedContainer(
            duration: const Duration(milliseconds: 180),
            padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 8),
            decoration: BoxDecoration(
              color: isSelected
                  ? _primary
                  : Colors.grey.shade100,
              borderRadius: BorderRadius.circular(12),
              border: Border.all(
                color: isSelected ? _primary : Colors.black12,
                width: isSelected ? 1.5 : 1,
              ),
            ),
            child: Row(
              children: [
                Icon(
                  p.icon,
                  size:  16,
                  color: isSelected ? Colors.white : Colors.black45,
                ),
                const SizedBox(width: 7),
                Expanded(
                  child: Text(
                    p.label,
                    style: TextStyle(
                      fontSize:   12,
                      fontWeight: FontWeight.w600,
                      color:      isSelected ? Colors.white : Colors.black54,
                    ),
                    overflow: TextOverflow.ellipsis,
                  ),
                ),
              ],
            ),
          ),
        );
      }).toList(),
    );
  }

  Widget _datePicker() {
    return GestureDetector(
      onTap: _pickDate,
      child: Container(
        padding: const EdgeInsets.all(14),
        decoration: BoxDecoration(
          color:        Colors.grey.shade50,
          border:       Border.all(color: Colors.black12),
          borderRadius: BorderRadius.circular(12),
        ),
        child: Row(children: [
          const Icon(Icons.calendar_today_rounded,
              color: _primary, size: 18),
          const SizedBox(width: 12),
          Expanded(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                const Text('Visit Date',
                    style: TextStyle(fontSize: 11, color: Colors.black45)),
                const SizedBox(height: 2),
                Text(
                  DateFormat('EEEE, d MMMM yyyy').format(_validDate),
                  style: const TextStyle(
                      fontSize: 14,
                      fontWeight: FontWeight.w600,
                      color:     Colors.black87),
                ),
              ],
            ),
          ),
          Container(
            padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 5),
            decoration: BoxDecoration(
                color:        _primary.withOpacity(0.1),
                borderRadius: BorderRadius.circular(8)),
            child: const Text('Change',
                style: TextStyle(
                    fontSize:   12,
                    color:      _primary,
                    fontWeight: FontWeight.w600)),
          ),
        ]),
      ),
    );
  }

  Widget _submitButton() {
    return SizedBox(
      width: double.infinity,
      height: 52,
      child: ElevatedButton(
        onPressed: _loading ? null : _submit,
        style: ElevatedButton.styleFrom(
          backgroundColor: _primary,
          foregroundColor: Colors.white,
          disabledBackgroundColor: _primary.withOpacity(0.5),
          elevation:  0,
          shape: RoundedRectangleBorder(
              borderRadius: BorderRadius.circular(14)),
        ),
        child: _loading
            ? const SizedBox(
            width:  22,
            height: 22,
            child:  CircularProgressIndicator(
                color: Colors.white, strokeWidth: 2.5))
            : const Row(
          mainAxisAlignment: MainAxisAlignment.center,
          children: [
            Text('Submit Request',
                style: TextStyle(
                    fontSize:   15,
                    fontWeight: FontWeight.w700)),
          ],
        ),
      ),
    );
  }
}